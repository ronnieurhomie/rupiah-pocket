import assert from 'node:assert/strict';
import {primaryRates, fallbackRates, restoreRates, selectedCurrencies, needsRefresh} from './rates.js';
const now = Date.parse('2026-11-16T12:00:00Z');
const primary = primaryRates({result: 'success', base_code: 'USD', time_last_update_unix: now / 1000, time_next_update_unix: now / 1000 + 86400, rates: {USD: 1, IDR: 16000, TWD: 32, MYR: 4.8, EUR: .9, JPY: 150, GBP: .8, INVALID: 3, ZZZ: -1, CAD: 0}});
assert.equal(primary.values.USD, 1 / 16000);
assert.equal(primary.values.TWD, .002);
assert.equal(primary.values.EUR, .9 / 16000);
assert.equal(primary.values.JPY, 150 / 16000);
assert.equal(primary.values.GBP, .8 / 16000);
assert(!('IDR' in primary.values));
assert(!('INVALID' in primary.values) && !('ZZZ' in primary.values) && !('CAD' in primary.values));
assert.throws(() => primaryRates({result: 'success', base_code: 'IDR', rates: {IDR: 1}}));
assert.throws(() => primaryRates({result: 'success', base_code: 'USD', time_last_update_unix: now / 1000, rates: {IDR: 16000}}));
const fallback = fallbackRates({date: '2026-11-16', idr: {usd: .00006, twd: .002, myr: .0003, eur: .00005, jpy: .009, idr: 1, bad: null}});
assert.equal(fallback.values.EUR, .00005);
assert.equal(fallback.values.JPY, .009);
assert(!('IDR' in fallback.values) && !('BAD' in fallback.values));
assert.throws(() => fallbackRates({date: 'bad', idr: {usd: 1}}));
const old = {usd: .00006, twd: .002, myr: .0003, dataTime: now - 1000, fetchedAt: now, nextUpdate: now + 86400000, source: 'erapi'};
const migrated = restoreRates(old);
assert.deepEqual(migrated.values, {USD: old.usd, TWD: old.twd, MYR: old.myr});
assert(needsRefresh(migrated, now));
assert.equal(restoreRates({dataTime: now, usd: -1, twd: 2, myr: 3}), null);
assert.equal(restoreRates(null), null);
assert.deepEqual(restoreRates({...primary, fetchedAt: now}).values, primary.values);
assert.deepEqual(selectedCurrencies(['EUR']), ['EUR']);
assert.deepEqual(selectedCurrencies(['JPY', 'GBP']), ['JPY', 'GBP']);
assert.deepEqual(selectedCurrencies(['EUR', 'USD', 'JPY', 'GBP']), ['EUR', 'USD', 'JPY']);
assert.deepEqual(selectedCurrencies(['USD', 'USD', 'IDR', null, 'xyz', 'EUR']), ['USD', 'EUR']);
assert.deepEqual(selectedCurrencies([]), ['USD', 'TWD', 'MYR']);
assert(!needsRefresh({...primary, fetchedAt: now}, now + 1000));
assert(needsRefresh({...primary, fetchedAt: now}, now + 86400000));
assert(needsRefresh({...primary, fetchedAt: now, nextUpdate: now - 1}, now));
assert(!needsRefresh({...fallback, fetchedAt: now}, now + 3599999));
assert(needsRefresh({...fallback, fetchedAt: now}, now + 3600000));
console.log('28 rates, preferences, migration, and freshness checks passed');
